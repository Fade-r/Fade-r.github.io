/* Build-time MathJax SVGs. Only generated HTML in the supplied site is changed. */
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const {createHash} = require("node:crypto");
const {mathjax} = require("mathjax-full/js/mathjax.js");
const {TeX} = require("mathjax-full/js/input/tex.js");
const {SVG} = require("mathjax-full/js/output/svg.js");
const {liteAdaptor} = require("mathjax-full/js/adaptors/liteAdaptor.js");
const {RegisterHTMLHandler} = require("mathjax-full/js/handlers/html.js");
const {AssistiveMmlHandler} = require("mathjax-full/js/a11y/assistive-mml.js");
const {AllPackages} = require("mathjax-full/js/input/tex/AllPackages.js");

const adaptor = liteAdaptor();
AssistiveMmlHandler(RegisterHTMLHandler(adaptor));
const tex = new TeX({
  packages: AllPackages,
  formatError: (_jax, error) => { throw error; },
});
// Local font paths are embedded in each SVG: no font download or shared URL.
const svg = new SVG({fontCache: "local"});
const document = mathjax.document("", {InputJax: tex, OutputJax: svg});

function decodeHTML(html) {
  return adaptor.textContent(adaptor.body(adaptor.parse(html, "text/html")));
}
function escapeAttribute(text) {
  return text.replace(/&/g, "&amp;").replace(/"/g, "&quot;")
    .replace(/</g, "&lt;").replace(/>/g, "&gt;");
}
function renderPage(html) {
  let count = 0;
  // These wrappers are generated by pymdownx.arithmatex, never arbitrary HTML.
  const output = html.replace(/<(span|div) class="arithmatex">([\s\S]*?)<\/\1>/g,
    (_match, tag, escaped) => {
      const source = decodeHTML(escaped).trim();
      const display = tag === "div";
      const open = display ? "\\[" : "\\(";
      const close = display ? "\\]" : "\\)";
      if (!source.startsWith(open) || !source.endsWith(close)) {
        throw new Error("Unexpected arithmatex delimiters: " + source.slice(0, 100));
      }
      const formula = source.slice(2, -2).trim();
      const node = document.convert(formula, {display});
      const markup = adaptor.outerHTML(node);
      if (markup.includes('data-mml-node="merror"')) {
        throw new Error("MathJax error: " + formula);
      }
      if (!markup.includes("<svg") || !markup.includes("<mjx-assistive-mml")) {
        throw new Error("Missing visible SVG or accessible MathML");
      }
      count++;
      const access = display ? ' tabindex="0" role="group" aria-label="公式，可横向滚动"' : "";
      return "<" + tag + ' class="arithmatex" data-math-rendered="svg" translate="no"' +
        ' data-tex="' + escapeAttribute(formula) + '"' + access + ">" + markup + "</" + tag + ">";
    });
  return {html: output, count};
}

function build(site) {
  site = path.resolve(site);
  if (!fs.existsSync(path.join(site, "index.html"))) throw new Error("Expected a built MkDocs site");
  const files = [];
  function walk(directory) {
    for (const entry of fs.readdirSync(directory, {withFileTypes: true}).sort((a,b)=>a.name.localeCompare(b.name))) {
      const file = path.join(directory, entry.name);
      if (entry.isSymbolicLink()) throw new Error("Symlinks are not allowed in the generated site");
      if (entry.isDirectory()) walk(file);
      else if (entry.name.endsWith(".html")) files.push(file);
    }
  }
  walk(site);
  // Convert everything before writing; a malformed equation fails the build.
  const pages = files.map(file => ({file, ...renderPage(fs.readFileSync(file, "utf8"))}));
  const total = pages.reduce((sum, page) => sum + page.count, 0);
  if (!total) throw new Error("No source equations found; run a clean MkDocs build first");
  const css = adaptor.textContent(svg.styleSheet(document));
  fs.writeFileSync(path.join(site, "assets/stylesheets/mathjax-svg.css"), css, "utf8");
  // Browsers may cache the previous extra.css while receiving new HTML.
  // Content hashes invalidate only the resources that actually changed.
  const resources = [
    "assets/stylesheets/mathjax-svg.css", "assets/stylesheets/extra.css",
    "assets/javascripts/theme-toggle.js", "assets/javascripts/signal-labs.js",
  ].map(file => [file, createHash("sha256").update(fs.readFileSync(path.join(site, file)))
    .digest("hex").slice(0, 12)]);
  for (const page of pages) {
    let html = page.html;
    for (const [file, hash] of resources) {
      html = html.split(file + '"').join(file + "?v=" + hash + '"');
    }
    fs.writeFileSync(page.file, html, "utf8");
  }
  console.log("Pre-rendered " + total + " equations across " + pages.filter(p=>p.count).length +
    " pages; SVG and accessible MathML are embedded, no browser math scripts.");
}

module.exports = {renderPage};
if (require.main === module) {
  try {
    if (process.argv.length !== 3) throw new Error("Usage: node render-math.cjs <built-site>");
    build(process.argv[2]);
  } catch (error) {
    console.error(error.stack);
    process.exitCode = 1;
  }
}
